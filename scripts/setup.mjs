#!/usr/bin/env node
import { createInterface } from 'node:readline/promises';
import { stdin, stdout } from 'node:process';
import { Writable } from 'node:stream';
import { randomBytes } from 'node:crypto';
import { chmod, readFile, writeFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = new Set(process.argv.slice(2));
const envFile = path.join(root, '.env');
const nonInteractive = process.env.SETUP_NONINTERACTIVE === 'true' || !stdin.isTTY;
const existing = await readFile(envFile, 'utf8').catch((error) => error.code === 'ENOENT' ? null : Promise.reject(error));
if (existing && !args.has('--force') && !nonInteractive) {
  console.error('.env already exists. Review it, then rerun with --force to intentionally replace setup configuration. Stop the panel before setup.');
  process.exit(2);
}
if (existing && nonInteractive && !args.has('--force')) {
  console.error('Refusing non-interactive setup over an existing .env without --force.');
  process.exit(2);
}
let muteOutput = false;
const rlOutput = new Writable({ write(chunk, _encoding, callback) { if (!muteOutput) stdout.write(chunk); callback(); } });
const rl = nonInteractive ? null : createInterface({ input: stdin, output: rlOutput });
async function ask(label, fallback, envName, secret = false) {
  if (nonInteractive) return process.env[envName] || fallback;
  const value = (await rl.question(`${label}${fallback ? ` [${fallback}]` : ''}: `)).trim();
  if (!value && !fallback && secret) throw new Error(`${label} is required.`);
  return value || fallback;
}
function validPassword(value) { return value.length >= 12 && value.length <= 256 && /[a-z]/.test(value) && /[A-Z]/.test(value) && /[0-9]/.test(value); }
function run(command, commandArgs) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, commandArgs, { cwd: root, stdio: 'inherit', env: process.env });
    child.once('error', reject); child.once('exit', (code) => code === 0 ? resolve() : reject(new Error(`${command} exited with ${code}`)));
  });
}
let adminPassword = '';
try {
  console.log('\nCerdasNet setup — stop any running panel process before continuing.\n');
  const siteName = await ask('Website name', 'CerdasNet', 'SITE_NAME');
  const siteTagline = await ask('Website tagline', 'VPS Control', 'SITE_TAGLINE');
  const appOriginInput = await ask('Public app URL', 'http://localhost:3000', 'APP_ORIGIN');
  const portInput = await ask('Node.js port', '3000', 'PORT');
  const adminUsername = await ask('Admin username', 'admin', 'ADMIN_USERNAME');
  const adminEmail = await ask('Admin email (optional, for Google Auth)', process.env.ADMIN_EMAIL || '', 'ADMIN_EMAIL');
  if (nonInteractive) adminPassword = process.env.ADMIN_PASSWORD || '';
  else {
    muteOutput = true;
    try { adminPassword = await rl.question('Admin password (min. 12 chars, upper/lowercase + number): '); }
    finally { muteOutput = false; stdout.write('\n'); }
  }
  if (nonInteractive && !adminPassword) throw new Error('ADMIN_PASSWORD is required for non-interactive setup.');
  if (!/^[a-zA-Z0-9._-]{3,64}$/.test(adminUsername)) throw new Error('Admin username must be 3–64 safe characters.');
  if (!validPassword(adminPassword)) throw new Error('Admin password does not meet the complexity requirements.');
  if (siteName.trim().length < 1 || siteName.length > 80 || siteTagline.trim().length < 1 || siteTagline.length > 120) throw new Error('Invalid website name/tagline.');
  if (adminEmail && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(adminEmail)) throw new Error('Invalid admin email.');
  const appOrigin = new URL(appOriginInput);
  if (!['http:', 'https:'].includes(appOrigin.protocol) || appOrigin.pathname !== '/' || appOrigin.search || appOrigin.hash) throw new Error('APP_ORIGIN must be an origin without path/query.');
  if (appOrigin.protocol !== 'https:' && !['localhost', '127.0.0.1'].includes(appOrigin.hostname)) throw new Error('Public production URL must use HTTPS.');
  const port = Number(portInput);
  if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error('Invalid Node.js port.');
  rl?.close();
  const values = {
    NODE_ENV: 'production', SITE_NAME: siteName.trim(), SITE_TAGLINE: siteTagline.trim(), APP_ORIGIN: appOrigin.origin,
    PORT: String(port), DATA_FILE: process.env.DATA_FILE || './data/database.json', TOKEN_ENCRYPTION_KEY: randomBytes(32).toString('hex'),
    COOKIE_SECURE: appOrigin.protocol === 'https:' ? 'true' : 'false', TRUST_PROXY: '1', LOG_LEVEL: 'info',
    SESSION_TTL_HOURS: '12', SYNC_INTERVAL_SECONDS: '300', SERVER_POLL_SECONDS: '30',
    METRICS_REFRESH_SECONDS: '300', METRICS_RETENTION_DAYS: '30', AUTO_SYNC_ON_BOOT: 'true',
  };
  const contents = `# Generated by npm run setup. Keep this file private.\n${Object.entries(values).map(([key, value]) => `${key}=${JSON.stringify(value)}`).join('\n')}\n`;
  await writeFile(envFile, contents, { mode: 0o600, flag: 'w' });
  await chmod(envFile, 0o600);
  for (const [key, value] of Object.entries(values)) process.env[key] = value;
  if (!args.has('--skip-install')) {
    await run('npm', ['ci', '--include=dev']);
    await run('npm', ['--prefix', 'backend', 'ci', '--include=dev']);
    await run('npm', ['--prefix', 'frontend', 'ci', '--include=dev']);
  }
  if (!args.has('--skip-build')) await run('npm', ['run', 'build']);
  const [{ loadConfig }, { createDatabase }, { bootstrapAdmin }, { BrandingService }] = await Promise.all([
    import('../backend/dist/config.js'), import('../backend/dist/db/index.js'),
    import('../backend/dist/auth/service.js'), import('../backend/dist/branding/service.js'),
  ]);
  const config = loadConfig({ ...process.env, SITE_NAME: siteName, SITE_TAGLINE: siteTagline, PORT: String(port), APP_ORIGIN: appOrigin.origin });
  const db = await createDatabase(config);
  try {
    const userCount = await db.read((data) => data.users.length);
    if (userCount === 0) await bootstrapAdmin(db, adminUsername, adminPassword, adminEmail || null);
    else console.log('Existing users detected; no password or role was changed.');
    const branding = new BrandingService(db, config);
    const current = await branding.get();
    await branding.update({ siteName, siteTagline, accent: current.accent, defaultTheme: current.defaultTheme });
  } finally { await db.close(); adminPassword = ''; }
  console.log(`\nSetup complete. Start with: node server.js\nURL: ${appOrigin.origin}\nNo admin password or encryption key was printed.`);
} catch (error) {
  rl?.close(); adminPassword = '';
  console.error(`Setup failed: ${error instanceof Error ? error.message : error}`);
  process.exitCode = 1;
}
